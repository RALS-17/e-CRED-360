export type CredentialStatus = 'verified' | 'pending' | 'expired' | 'missing' | 'expiring';

/** Active Physician · Visiting Physician · Applicant */
export type ProviderStatus = 'active' | 'visiting' | 'applicant';

export interface Credential {
  id: string;
  type: string;
  number: string;
  issuer: string;
  issueDate: string;
  expiryDate: string;
  status: CredentialStatus;
  verifiedAt?: string;
  verifiedBy?: string;
  fileUrl?: string;
  /** Checklist: marked complete / on file */
  checked?: boolean;
}

export interface Privilege {
  department: string;
  privilege: string;
  status: 'granted' | 'pending' | 'denied' | 'expired';
  grantedDate?: string;
  expiryDate?: string;
}

/** Application / onboarding requirement (diploma, TOR, NBI, etc.) */
export interface RequirementItem {
  id: string;
  label: string;
  description?: string;
  completed: boolean;
  completedAt?: string;
  required: boolean;
}

export interface Provider {
  id: string;
  name: string;
  specialty: string;
  prcNumber: string;
  philHealthNumber?: string;
  status: ProviderStatus;
  department: string;
  credentials: Credential[];
  privileges: Privilege[];
  /** Application requirements checklist (especially for applicants) */
  requirements: RequirementItem[];
  lastReviewed: string;
  complianceScore: number;
  photoInitials: string;
}

